import pandas as pd
import matplotlib.pyplot as plt

# 1. Provide the raw data (Revenue and Operating Profit)
data = {
    'Period': ['FY22 Q1', 'FY22 Q2', 'FY22 Q3', 'FY22 Q4',
               'FY23 Q1', 'FY23 Q2', 'FY23 Q3', 'FY23 Q4',
               'FY24 Q1', 'FY24 Q2', 'FY24 Q3', 'FY24 Q4',
               'FY25 Q1', 'FY25 Q2', 'FY25 Q3', 'FY25 Q4',
               'FY26 Q1', 'FY26 Q2', 'FY26 Q3', 'FY26 Q4'],
    'Revenue': [200680, 206550, 223310, 225970, 234640, 246860, 267000, 266060,
                262960, 266720, 284460, 284990, 280570, 288620, 298860, 302600,
                303490, 308200, 314500, 318900],
    'Operating_Profit': [39310, 40140, 43970, 44050, 39920, 44250, 52230, 48380,
                         44600, 49390, 56150, 50180, 47270, 50290, 55430, 54390,
                         49420, 51400, 56300, 55700]
}
df = pd.DataFrame(data)

# 2. Calculate the Operating Margin Percentage
df['Operating_Margin_%'] = (df['Operating_Profit'] / df['Revenue']) * 100

# 3. Set up the chart
plt.figure(figsize=(14, 6))

# 4. Plot the margin and add a dotted line for the Average
plt.plot(df['Period'], df['Operating_Margin_%'], marker='o', color='#dc3545', linewidth=2.5, label='Operating Margin %')
plt.axhline(y=df['Operating_Margin_%'].mean(), color='black', linestyle='--', linewidth=1.5, label='Average Margin')

# 5. Format the chart
plt.title('HCLTech Operating Margin Trend (Anomaly Detection)', fontsize=14, fontweight='bold')
plt.xlabel('Financial Quarter', fontsize=12)
plt.ylabel('Margin (%)', fontsize=12)
plt.xticks(rotation=45)
plt.grid(axis='y', linestyle='--', alpha=0.7)
plt.legend(fontsize=12)
